// 把真实抓包字节流喂给 DownParser，验证解析器本身
#include <nav/frame.hpp>
#include <cstdio>
#include <cstdint>

int main() {
  // 抓包开头的连续字节流（三帧：状态、机器人、0x0010）
  const uint8_t stream[] = {
      0xa5, 0x0b, 0x00, 0xfb, 0x56, 0x01, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x0d, 0x53,  // 比赛状态 20B
      0xa5, 0x0d, 0x00, 0xfc, 0x04, 0x0b, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x53, 0x31,                                                    // 机器人状态 22B
      0xa5, 0x10, 0x00, 0xfd, 0x00, 0x10, 0x00, 0xfa, 0x9d, 0xe5,
      0xb9, 0x43, 0xdc, 0x62, 0x38, 0x89, 0x4b, 0xc3, 0x3c, 0xc4,
      0x12, 0x04, 0xbe, 0x02, 0x5c,                                // 0x0010 帧 25B
  };

  nav::DownParser p;
  const auto frames = p.feed(stream, sizeof(stream));
  printf("喂入 %zu 字节，解析出 %zu 帧\n", sizeof(stream), frames.size());
  printf("crc8错误=%zu crc16错误=%zu 重同步丢字节=%zu\n",
         p.crc8_errors(), p.crc16_errors(), p.resync_drops());
  for (const auto& f : frames) {
    printf("  cmd_id=%#06x data长度=%zu data[0]=%#04x → game_progress=%u\n",
           f.cmd_id, f.data.size(),
           f.data.empty() ? 0 : f.data[0],
           f.data.empty() ? 0 : nav::game_progress_of(f.data[0]));
  }
  return 0;
}
